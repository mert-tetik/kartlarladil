export function getAdditionalCardExamples(
  englishKey: string,
  language: LanguageCode,
  term: string,
): readonly [string, string] | null {
  const style = getAdditionalCardExampleStyle(englishKey);
  if (!style) {
    return null;
  }

  const templates = TEMPLATES[language][style];
  return templates.map((sentence) => sentence.replaceAll("{term}", term)) as [string, string];
}
